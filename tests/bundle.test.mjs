// core_db/tests/bundle.test.mjs — dist/core_db.js: banner, up to date with src/, and it loads in plain Node with
// the FiveM globals shimmed (like core's old pg_smoke.js), registering every export and answering a query.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { BASE_URL, EXPORTS } from './helpers.mjs';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIST = path.join(ROOT, 'dist', 'core_db.js');
const BANNER = "// fxlint-disable-file: generated by 'npm run build' (core_db/build) from src/ - edit the source, not this file.";

test('the bundle has the banner and matches a fresh build of src/', () => {
    const text = fs.readFileSync(DIST, 'utf8');
    assert.equal(text.split('\n', 1)[0], BANNER);
    const esbuild = require('esbuild');
    const fresh = esbuild.buildSync({
        entryPoints: [path.join(ROOT, 'src', 'index.js')],
        bundle: true, platform: 'node', target: 'node22', format: 'cjs', external: ['pg-native'],
        banner: { js: BANNER }, write: false, logLevel: 'silent', absWorkingDir: path.join(ROOT, 'build'),
    });
    assert.equal(fresh.outputFiles[0].text, text, 'dist/core_db.js is stale — run: npm run build -w core_db-build');
});

function loadBundle(url) {
    const registered = {};
    const handlers = {};
    const logs = [];
    globalThis.GetCurrentResourceName = () => 'core_db';
    globalThis.GetInvokingResource = () => 'core';
    globalThis.GetConvar = (name, fallback) => (name === 'core_pg_url' ? url : fallback);
    globalThis.LoadResourceFile = () => null;
    globalThis.GetResourceState = () => 'started';
    globalThis.GetNumResourceMetadata = () => 0;
    globalThis.GetResourceMetadata = () => null;
    globalThis.exports = (name, fn) => { registered[name] = fn; };
    globalThis.on = (name, fn) => { handlers[name] = fn; };
    globalThis.emit = () => {};
    const original = { log: console.log, warn: console.warn, error: console.error };
    console.log = (...a) => logs.push(a.join(' '));
    console.warn = console.log;
    console.error = console.log;
    try {
        delete require.cache[DIST];
        require(DIST);
    } finally {
        Object.assign(console, original);
    }
    return { registered, handlers, logs };
}

test('the bundle loads in plain Node, registers every export and answers a query', async () => {
    const { registered, handlers, logs } = loadBundle(BASE_URL);
    assert.deepEqual(Object.keys(registered), EXPORTS, 'no test exports in the real entry');
    assert.deepEqual(Object.keys(handlers).sort(), ['onResourceStart', 'onResourceStop', 'txAdmin:events:serverShuttingDown']);
    assert.ok(logs.some((l) => l.startsWith('[core_db] ready (pool 10, flush 250 ms, statement timeout 10000 ms)')));
    assert.ok(!logs.some((l) => l.includes('core_test:core_test')), 'the URL is never logged');
    const answer = await new Promise((resolve) => registered.query('SELECT 41 + 1 AS n, now() AS t', [], null, (...a) => resolve(a)));
    assert.equal(answer[0], null);
    assert.equal(answer[1][0].n, 42);
    assert.equal(typeof answer[1][0].t, 'number');
    assert.deepEqual(registered.enqueue([]), { seq: 0 });
    assert.equal(registered.isHealthy(), true);
    handlers.onResourceStop('core_db');
});

test('the bundle without core_pg_url answers unavailable', async () => {
    const { registered, logs } = loadBundle('');
    assert.ok(logs.some((l) => l.includes('core_pg_url is not set')));
    const answer = await new Promise((resolve) => registered.query('SELECT 1', [], null, (...a) => resolve(a)));
    assert.deepEqual(answer, ['unavailable']);
});
